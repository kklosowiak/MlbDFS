"""Full-season signal audit on dataset_*.csv. Date-clustered bootstrap CIs (players on one day are correlated).
Writes reports/season_2026_signal_audit.md. ASCII only."""
import os
import sys
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data", "season_2026")
RNG = np.random.default_rng(7)
NB = 2000

BUY_H = ["is_hot_run_msmi", "smash_factor", "is_anti_chalk_smash", "is_juiced_target", "is_speed_target",
         "is_pitch_alignment", "walks_boost", "is_hot", "is_prop_juice", "is_ELITE_PLATOON", "is_STRONG_EDGE"]
AVOID_H = ["is_cold_streak_msmi", "is_cold_high_br_warning", "is_PLATOON_TRAP", "strikeouts_penalty"]
BUY_T = ["is_hot_run_msmi", "is_burst", "is_pitch_alignment", "is_sharp", "is_anti_chalk_smash", "is_physics_override",
         "is_pinnacle_offense_boost", "is_velocity_boost"]
AVOID_T = ["is_cold_streak", "is_cold_streak_msmi", "is_fade_risk", "is_public_steam_trap", "is_fatigued"]
AVOID_P = ["is_trap", "is_hazard", "is_low_ceiling", "is_high_variance", "is_volatile", "sticky_trap", "sharp_fade"]
BUY_P = ["is_sharp", "is_juiced_target", "is_prop_juice"]


def clus_diff(y, m, dates):
    """mean(y[m]) - mean(y[~m]) with date-cluster bootstrap CI. Returns (diff, lo, hi, n_m)."""
    y = np.asarray(y, float)
    m = np.asarray(m, bool)
    ud, inv = np.unique(dates, return_inverse=True)
    k = len(ud)
    sf = np.bincount(inv, weights=y * m, minlength=k)
    nf = np.bincount(inv, weights=m.astype(float), minlength=k)
    sn = np.bincount(inv, weights=y * ~m, minlength=k)
    nn = np.bincount(inv, weights=(~m).astype(float), minlength=k)
    if nf.sum() == 0 or nn.sum() == 0:
        return np.nan, np.nan, np.nan, int(nf.sum())
    pt = sf.sum() / nf.sum() - sn.sum() / nn.sum()
    idx = RNG.integers(0, k, size=(NB, k))
    a, b, c, d = sf[idx].sum(1), nf[idx].sum(1), sn[idx].sum(1), nn[idx].sum(1)
    ok = (b > 0) & (d > 0)
    bs = a[ok] / b[ok] - c[ok] / d[ok]
    return pt, np.percentile(bs, 2.5), np.percentile(bs, 97.5), int(nf.sum())


def verdict(pt, lo, hi, n, direction):
    if n < 30 or np.isnan(pt):
        return "insufficient (n<30)"
    if lo > 0:
        sig = "pos"
    elif hi < 0:
        sig = "neg"
    else:
        sig = "none"
    if direction == "?":
        return {"pos": "positive", "neg": "negative", "none": "no detectable edge"}[sig]
    want = "pos" if direction == "buy" else "neg"
    if sig == "none":
        return "no detectable edge"
    return "WORKS" if sig == want else "REVERSED"


def signal_table(df, flags, directions, ycols, dates_col="date"):
    rows = []
    for f in flags:
        m = df[f].astype(bool).values
        r = {"signal": f, "dir": directions.get(f, "?"), "fires": int(m.sum()),
             "days": df.loc[m, dates_col].nunique()}
        for name, col in ycols:
            pt, lo, hi, n = clus_diff(df[col].values, m, df[dates_col].values)
            r[name] = "%+.2f [%+.2f, %+.2f]" % (pt, lo, hi) if not np.isnan(pt) else "n/a"
            r["_" + name] = (pt, lo, hi, n)
        main = ycols[0][0]
        r["verdict"] = verdict(*r["_" + main], directions.get(f, "?"))
        rows.append(r)
    return rows


def md_table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def per_date_spearman(df, score, y, dates_col="date", min_n=6):
    vals = []
    for d, g in df.groupby(dates_col):
        g = g[[score, y]].dropna()
        if len(g) >= min_n and g[score].nunique() > 1 and g[y].nunique() > 1:
            vals.append(g[score].rank().corr(g[y].rank()))
    vals = np.array(vals)
    if len(vals) < 5:
        return np.nan, np.nan, np.nan, len(vals)
    bs = [vals[RNG.integers(0, len(vals), len(vals))].mean() for _ in range(NB)]
    return vals.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5), len(vals)


def corr_table(df, scores, y):
    rows = []
    for s in scores:
        pt, lo, hi, k = per_date_spearman(df, s, y)
        rows.append({"score": s, "avg_daily_spearman": "%+.3f [%+.3f, %+.3f]" % (pt, lo, hi) if not np.isnan(pt) else "n/a",
                     "days": k})
    return rows


def main():
    H = pd.read_csv(os.path.join(D, "dataset_hitters.csv"))
    T = pd.read_csv(os.path.join(D, "dataset_teams.csv"))
    P = pd.read_csv(os.path.join(D, "dataset_pitchers.csv"))
    L = []
    L.append("# OMEGA 2026 Full-Season Signal Audit (Jul 2 - Oct 28 lock snapshots)\n")
    L.append("Generated by `scripts/season_signal_audit.py` from `data/season_2026/dataset_*.csv` "
             "(lock snapshot joined to MLB StatsAPI box scores). CIs are 95%% date-clustered bootstraps (%d resamples). "
             "Regular-season games only; doubleheader-team rows excluded.\n" % NB)

    # ---------------- hitters ----------------
    H = H[(H.game_type == "R") & (H.dh == 0)].copy()
    for lab in ("ELITE PLATOON", "STRONG EDGE", "PLATOON TRAP"):
        H["is_" + lab.replace(" ", "_")] = (H.platoon_label == lab).astype(int)
    Hp = H[H.played == 1].copy()
    base_by_order = Hp.groupby("actual_order").actual_dk.mean()
    Hp["resid"] = Hp.actual_dk - Hp.actual_order.map(base_by_order)
    Hp["hit15"] = (Hp.actual_dk >= 15).astype(float)
    Hp["hit20"] = (Hp.actual_dk >= 20).astype(float)
    H["actual_dk0"] = H.actual_dk.fillna(0.0)
    H["hit15_all"] = (H.actual_dk0 >= 15).astype(float)
    L.append("## 1. Hitters\n")
    L.append("Rows: %d played hitter-games on %d dates (%d rows with no box-score line = DNP, %.1f%%). "
             "Mean DK pts %.2f; share >=15 pts %.1f%%; >=20 pts %.1f%%.\n" %
             (len(Hp), Hp.date.nunique(), (H.played == 0).sum(), 100 * (H.played == 0).mean(), Hp.actual_dk.mean(),
              100 * Hp.hit15.mean(), 100 * Hp.hit20.mean()))
    L.append("Metrics: **resid** = DK pts minus the league mean for that batting-order spot (controls for opportunity); "
             "**p15/p20** = change in probability of a 15+/20+ pt game (percentage points, flagged minus unflagged). "
             "Verdict uses the resid CI and the intended direction.\n")
    dirs = {**{k: "buy" for k in BUY_H}, **{k: "avoid" for k in AVOID_H}}
    Hp["p15"] = Hp.hit15 * 100
    Hp["p20"] = Hp.hit20 * 100
    rows = signal_table(Hp, BUY_H + AVOID_H, dirs, [("resid", "resid"), ("p15", "p15"), ("p20", "p20")])
    L.append(md_table(rows, ["signal", "dir", "fires", "days", "resid", "p15", "p20", "verdict"]) + "\n")
    L.append("\n### Hitter score rank power (average daily Spearman vs DK pts, played hitters)\n")
    L.append(md_table(corr_table(Hp, ["blended_rating", "player_score", "stack_adjusted_score", "attack_conf",
                                      "physics_score", "market_score", "matchup_xwoba", "recent_ops", "season_ops",
                                      "platoon_multiplier", "barrel_pct", "hard_hit_pct"], "actual_dk"),
                      ["score", "avg_daily_spearman", "days"]) + "\n")
    L.append("\n### Ceiling by blended_rating bucket (all hitters incl. DNP as 0)\n")
    H["br_bucket"] = pd.qcut(H.blended_rating.rank(method="first"), 5, labels=["Q1 low", "Q2", "Q3", "Q4", "Q5 high"])
    g = H.groupby("br_bucket", observed=True).agg(n=("actual_dk0", "size"), mean_dk=("actual_dk0", "mean"),
                                                   p15=("hit15_all", "mean"))
    g["p15"] = (g.p15 * 100).round(1)
    g["mean_dk"] = g.mean_dk.round(2)
    L.append(md_table([{"bucket": i, **r} for i, r in g.reset_index().set_index("br_bucket").iterrows()],
                      ["bucket", "n", "mean_dk", "p15"]) + "\n")
    H["day_rank"] = H.groupby("date").blended_rating.rank(ascending=False, method="first")
    top = H[H.day_rank <= 10]
    L.append("\nTop-10 hitters per day by blended_rating: n=%d, mean DK %.2f vs all hitters %.2f; p(15+) %.1f%% vs %.1f%%; "
             "DNP rate %.1f%%.\n" % (len(top), top.actual_dk0.mean(), H.actual_dk0.mean(), 100 * top.hit15_all.mean(),
                                      100 * H.hit15_all.mean(), 100 * (top.played == 0).mean()))

    # ---------------- teams ----------------
    T = T[(T.game_type == "R") & (T.dh == 0)].copy()
    T["resid_itt"] = T.actual_runs - T.implied_total
    T["p5"] = (T.actual_runs >= 5).astype(float) * 100
    T["p7"] = (T.actual_runs >= 7).astype(float) * 100
    L.append("\n## 2. Team stacks\n")
    L.append("Rows: %d team-games on %d dates. Mean runs %.2f vs mean implied total %.2f. Share >=5 runs %.1f%%, >=7 runs %.1f%%.\n" %
             (len(T), T.date.nunique(), T.actual_runs.mean(), T.implied_total.mean(), T.p5.mean(), T.p7.mean()))
    L.append("**runs-ITT** = actual runs minus Vegas implied total (does the signal beat the market?); "
             "p5/p7 = change in probability of 5+/7+ runs (pts).\n")
    dirs_t = {**{k: "buy" for k in BUY_T}, **{k: "avoid" for k in AVOID_T}}
    rows = signal_table(T, BUY_T + AVOID_T + ["is_trap", "is_shark", "is_steam", "is_gassed", "is_volatile", "is_blind_spot",
                                              "is_true_talent_penalty"], dirs_t,
                        [("runs_ITT", "resid_itt"), ("p5", "p5"), ("p7", "p7")])
    L.append(md_table(rows, ["signal", "dir", "fires", "days", "runs_ITT", "p5", "p7", "verdict"]) + "\n")
    L.append("\n### Team score rank power (average daily Spearman vs actual runs)\n")
    L.append(md_table(corr_table(T, ["implied_total", "blended_rating", "attack_conf", "stack_score", "stack_score_raw",
                                     "stack_trust_score", "physics_score", "market_score", "team_xwoba", "divergence",
                                     "power_concentration", "bullpen_boost", "vulnerability"], "actual_runs"),
                      ["score", "avg_daily_spearman", "days"]) + "\n")
    L.append("\n### Top-ranked stack per day (the pick that matters for a single lineup)\n")
    rows = []
    for metric in ["implied_total", "blended_rating", "attack_conf", "stack_score", "stack_trust_score"]:
        picks = T.sort_values([metric, "blended_rating"], ascending=False).groupby("date").head(1)
        rows.append({"rank_by": metric, "days": len(picks), "mean_runs": "%.2f" % picks.actual_runs.mean(),
                     "p5": "%.1f%%" % picks.p5.mean(), "p7": "%.1f%%" % picks.p7.mean(),
                     "runs_minus_ITT": "%+.2f" % picks.resid_itt.mean()})
    rows.append({"rank_by": "(all teams)", "days": T.date.nunique(), "mean_runs": "%.2f" % T.actual_runs.mean(),
                 "p5": "%.1f%%" % T.p5.mean(), "p7": "%.1f%%" % T.p7.mean(), "runs_minus_ITT": "%+.2f" % T.resid_itt.mean()})
    L.append(md_table(rows, ["rank_by", "days", "mean_runs", "p5", "p7", "runs_minus_ITT"]) + "\n")

    # ---------------- pitchers ----------------
    P = P[(P.game_type == "R") & (P.dh == 0)].copy()
    Ps = P[P.started == 1].copy()
    Ps["resid_proj"] = Ps.actual_dk - Ps.dk_points_mean
    Ps["bust"] = (Ps.actual_dk <= 10).astype(float) * 100
    Ps["p25"] = (Ps.actual_dk >= 25).astype(float) * 100
    L.append("\n## 3. Pitchers\n")
    L.append("Rows: %d starts on %d dates. Mean DK %.2f; bust (<=10) %.1f%%; ceiling (>=25) %.1f%%. "
             "Model projection `dk_points_mean` mean %.2f (bias %+.2f).\n" %
             (len(Ps), Ps.date.nunique(), Ps.actual_dk.mean(), Ps.bust.mean(), Ps.p25.mean(),
              Ps.dk_points_mean.mean(), Ps.actual_dk.mean() - Ps.dk_points_mean.mean()))
    dirs_p = {**{k: "avoid" for k in AVOID_P}, **{k: "buy" for k in BUY_P}}
    rows = signal_table(Ps, AVOID_P + BUY_P + ["is_paradox", "is_debut", "is_coors", "is_outlier_driven"], dirs_p,
                        [("dk_pts", "actual_dk"), ("bust%", "bust"), ("p25", "p25")])
    L.append(md_table(rows, ["signal", "dir", "fires", "days", "dk_pts", "bust%", "p25", "verdict"]) + "\n")
    L.append("\n### Pitcher score rank power (average daily Spearman vs DK pts)\n")
    L.append(md_table(corr_table(Ps, ["blended_rating", "attack_conf", "alpha_score", "physics_score", "market_score",
                                      "dk_points_mean", "siera", "csw", "k_line", "outs_line", "bm_score"], "actual_dk"),
                      ["score", "avg_daily_spearman", "days"]) + "\n")
    Ps["pred_bucket"] = pd.qcut(Ps.dk_points_mean.rank(method="first"), 5, labels=["Q1", "Q2", "Q3", "Q4", "Q5"])
    g = Ps.groupby("pred_bucket", observed=True).agg(n=("actual_dk", "size"), proj=("dk_points_mean", "mean"),
                                                      actual=("actual_dk", "mean"))
    L.append("\n### Projection calibration (`dk_points_mean` quintiles)\n")
    L.append(md_table([{"quintile": i, "n": r.n, "proj": "%.1f" % r.proj, "actual": "%.1f" % r.actual}
                       for i, r in g.iterrows()], ["quintile", "n", "proj", "actual"]) + "\n")

    path = os.path.join(ROOT, "reports", "season_2026_signal_audit.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote", path)


if __name__ == "__main__":
    main()
